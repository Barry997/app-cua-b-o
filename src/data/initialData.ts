// Helper để tính điểm trung bình demo
export function calculateAverageScore(
  regularScores: number[],
  midterm: number | null,
  final: number | null,
  config: GradeConfig = DEFAULT_GRADE_CONFIG
): number | null {
  if (midterm === null || final === null || regularScores.length === 0) {
    return null;
  }
  const regAvg = regularScores.reduce((a, b) => a + b, 0) / regularScores.length;
  const totalWeight = config.regularWeight + config.midtermWeight + config.finalWeight;
  const weighted =
    regAvg * config.regularWeight +
    midterm * config.midtermWeight +
    final * config.finalWeight;
  return Math.round((weighted / totalWeight) * 10) / 10;
}

